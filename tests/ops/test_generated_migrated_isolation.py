"""migrated 告警不命中平台路由、不當 inhibit source（#4355）——由產生器的輸出推導。

名單不手寫：每條平台路由、每條 inhibit rule 都從產生器實際 render 出的設定讀，
以後新增的平台路由或 base 的 inhibit rule 自動進到檢查裡。

兩層，判準不同：

1. **本檔（純 Python，不需 docker、不需 Go）**：對 render 出的設定做結構判定——
   取每條平台路由的等號 matcher，加上 ``da_migrated="true"`` 與租戶，以
   ``_grar_validate._matcher_matches_labels``（與 Watchdog 守衛同一份 matcher
   語意）走 route tree 的第一層：影子期租戶只能落在 migrated 影子路由；已切換
   （active）的租戶不能落在任何一條平台路由。inhibit：每條規則的 source 加上
   ``da_migrated="true"`` 後不再成立。
2. **Alertmanager 自己的程式碼**：本檔把同一份 render 寫成
   ``tests/alertmanager-inhibit/testdata/generated_migrated_alertmanager.yaml``
   （與產生器輸出不同就紅），``TestGeneratedMigratedRouting`` 以
   ``dispatch.Route.Match``、``TestGeneratedMigratedInhibit`` 以
   ``inhibit.Inhibitor`` 判同一件事（``go test``，CI 的 small Go modules job）。
   重產：

       python3 tests/ops/test_generated_migrated_isolation.py

租戶 ``ta`` 在影子期、``tb`` 已切換；fixture 名稱刻意不用真實租戶 id（dev-rules #9）。
"""
from __future__ import annotations

import os
import sys
from pathlib import Path

import pytest
import yaml

REPO = Path(__file__).resolve().parents[2]
for _p in (REPO / "scripts" / "tools", REPO / "scripts" / "tools" / "ops"):
    if str(_p) not in sys.path:
        sys.path.insert(0, str(_p))

from _grar_render import (  # noqa: E402
    PLATFORM_ROUTE_COUNT,
    assemble_alertmanager_yml,
    load_base_config,
)
from _grar_routes import (  # noqa: E402
    MIGRATED_LABEL,
    MIGRATED_SHADOW_RECEIVER,
    MIGRATED_VALUE,
    generate_inhibit_rules,
    generate_routes,
)
from _grar_validate import _INHIBIT_MATCHER_RE, _matcher_matches_labels  # noqa: E402

FIXTURE = (REPO / "tests" / "alertmanager-inhibit" / "testdata"
           / "generated_migrated_alertmanager.yaml")
BASE_CM = REPO / "k8s" / "03-monitoring" / "configmap-alertmanager.yaml"

SHADOW, ACTIVE = "ta", "tb"

_HEADER = (
    "# GENERATED by tests/ops/test_generated_migrated_isolation.py from the\n"
    "# deployed base (k8s/03-monitoring/configmap-alertmanager.yaml) and the\n"
    "# route generator — do not edit; regenerate with:\n"
    "#   python3 tests/ops/test_generated_migrated_isolation.py\n"
    f"# tenants: {SHADOW}=shadow {ACTIVE}=active; enforced NOC on critical (#4355)\n"
)


def render() -> str:
    """The alertmanager.yml the generator writes for the fixture tenants."""
    routing = {t: {"receiver": {"type": "webhook", "url": f"https://hooks.example.com/{t}"}}
               for t in (SHADOW, ACTIVE)}
    enforced = {"receiver": {"type": "webhook", "url": "https://noc.example.com/alerts"},
                "match": ['severity="critical"']}
    routes, receivers, warnings = generate_routes(routing, enforced_routing=enforced, tenants=())
    assert not [w for w in warnings if "skipping" in w or "blocked" in w], warnings
    inhibit, _ = generate_inhibit_rules({t: "enable" for t in (SHADOW, ACTIVE)})
    base_text = yaml.safe_load(BASE_CM.read_text(encoding="utf-8"))["data"]["alertmanager.yml"]
    body = assemble_alertmanager_yml(load_base_config(base_text), routes, receivers, inhibit,
                                     strict=True, migrated_active=[ACTIVE])
    return _HEADER + body


@pytest.fixture(scope="module")
def am() -> dict:
    return yaml.safe_load(render())


def _equalities(matchers: list[str]) -> dict[str, str]:
    """The non-empty ``name="value"`` matchers, as labels."""
    out = {}
    for m in matchers or []:
        parsed = _INHIBIT_MATCHER_RE.match(m)
        if parsed and parsed.group(2) == "=" and parsed.group(3):
            out[parsed.group(1)] = parsed.group(3)
    return out


def _matches(route: dict, labels: dict[str, str]) -> bool:
    return all(_matcher_matches_labels(m, labels) for m in route.get("matchers") or [])


def _platform(am: dict) -> list[dict]:
    return am["route"]["routes"][:PLATFORM_ROUTE_COUNT]


def _probes(am: dict, tenant: str) -> list[tuple[int, dict[str, str]]]:
    """One migrated alert per platform route: the labels that route matches
    on, a migrated alert's mark and *tenant*."""
    return [(i, {"alertname": "MigratedProbe", "severity": "critical",
                 **_equalities(r.get("matchers")),
                 MIGRATED_LABEL: MIGRATED_VALUE, "tenant": tenant})
            for i, r in enumerate(_platform(am))]


def test_the_fixture_is_the_generators_output():
    assert FIXTURE.is_file(), (
        f"{FIXTURE.relative_to(REPO)} is missing; run: "
        "python3 tests/ops/test_generated_migrated_isolation.py")
    assert FIXTURE.read_text(encoding="utf-8") == render(), (
        f"{FIXTURE.relative_to(REPO)} is not what the generator renders now; run: "
        "python3 tests/ops/test_generated_migrated_isolation.py")


def test_the_platform_routes_end_with_the_migrated_one(am):
    """The Go side reads the platform routes as those up to and including the
    migrated shadow route: that shape is pinned here."""
    names = [r.get("receiver") for r in _platform(am)]
    assert names[-1] == MIGRATED_SHADOW_RECEIVER, names
    assert MIGRATED_SHADOW_RECEIVER not in [r.get("receiver")
                                            for r in am["route"]["routes"][PLATFORM_ROUTE_COUNT:]]


def test_a_shadow_tenants_migrated_alert_reaches_only_the_shadow_route(am):
    for i, labels in _probes(am, SHADOW):
        first = next(j for j, r in enumerate(am["route"]["routes"]) if _matches(r, labels))
        assert am["route"]["routes"][first]["receiver"] == MIGRATED_SHADOW_RECEIVER, (
            f"a migrated alert shaped like platform route {i} ({labels}) is taken by "
            f"route {first} ({am['route']['routes'][first].get('matchers')})")


def test_a_cut_over_tenants_migrated_alert_matches_no_platform_route(am):
    for i, labels in _probes(am, ACTIVE):
        hit = [j for j, r in enumerate(_platform(am)) if _matches(r, labels)]
        assert hit == [], (f"a cut-over tenant's migrated alert shaped like platform route "
                           f"{i} ({labels}) is taken by platform route(s) {hit}")


def test_the_probes_reach_their_routes_without_the_mark(am):
    """Control: without the migrated mark each probe IS its route's alert, so
    the checks above measure the gate, not a probe that matches nothing."""
    for i, labels in _probes(am, SHADOW)[:-1]:
        plain = {k: v for k, v in labels.items() if k != MIGRATED_LABEL}
        first = next(j for j, r in enumerate(am["route"]["routes"]) if _matches(r, plain))
        assert first == i, (i, first, plain)


def test_a_migrated_source_mutes_nothing(am):
    """Every inhibit rule of the output (the base's and the generated): its
    source, as the alert it names, no longer matches once it carries the
    migrated mark — and does match without it (the control)."""
    rules = am["inhibit_rules"]
    assert rules
    for i, rule in enumerate(rules):
        src = {"tenant": SHADOW, **_equalities(rule["source_matchers"])}
        for m in rule["source_matchers"]:
            parsed = _INHIBIT_MATCHER_RE.match(m)
            if parsed and parsed.group(2) == "=~" and parsed.group(1) not in src:
                src[parsed.group(1)] = "x"
        assert all(_matcher_matches_labels(m, src) for m in rule["source_matchers"]), (i, src)
        marked = {**src, MIGRATED_LABEL: MIGRATED_VALUE}
        assert not all(_matcher_matches_labels(m, marked) for m in rule["source_matchers"]), (
            f"inhibit_rules[{i}]: a migrated alert {marked} is its source")


