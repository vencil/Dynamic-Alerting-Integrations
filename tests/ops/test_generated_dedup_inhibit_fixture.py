"""產生器真實輸出的 severity dedup inhibit rule，交給 Alertmanager 的 matcher 判（#3899）。

#3899 之前，`tests/alertmanager-inhibit` 的 dedup 語意測試讀的是 base
ConfigMap 裡兩條手寫的 per-tenant 規則；那兩條拿掉之後（base 不可再放 dedup
規則，`merge_generated` 會拒收），語意要改由**產生器的輸出**證明。

本檔用一組固定的 dedup_configs 呼叫 `generate_inhibit_rules`，把結果寫成
`tests/alertmanager-inhibit/testdata/generated_dedup_inhibit.yaml`；Go 端
（`TestGeneratedDedupSemantics`、`TestEveryInhibitRuleIsTenantScoped`、
`TestEveryEqualLabelIsGated`）讀同一份檔，用 Alertmanager 自己的 matcher 判。
檔案與產生器輸出不同就紅（drift），重產：

    python3 tests/ops/test_generated_dedup_inhibit_fixture.py

四個租戶各代表一種 mode：`ta`／`td` enable、`tb` disable、`tc` None
（#3621：樹被拒、沒讀到 mode）。fixture 名稱刻意不用真實租戶 id（dev-rules #9）。
"""
from __future__ import annotations

import os
import sys
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parents[2]
for _p in (REPO / "scripts" / "tools", REPO / "scripts" / "tools" / "ops"):
    if str(_p) not in sys.path:
        sys.path.insert(0, str(_p))

from _grar_routes import generate_inhibit_rules  # noqa: E402
from _grar_validate import (  # noqa: E402
    find_ungated_equal_label_inhibits,
    is_generated_dedup_rule,
)

FIXTURE = REPO / "tests" / "alertmanager-inhibit" / "testdata" / "generated_dedup_inhibit.yaml"

#: The modes the fixture is generated from. The Go side names the same ids.
DEDUP_CONFIGS: dict[str, str | None] = {
    "ta": "enable",
    "tb": "disable",
    "tc": None,
    "td": "enable",
}

_HEADER = (
    "# GENERATED by tests/ops/test_generated_dedup_inhibit_fixture.py from\n"
    "# _grar_routes.generate_inhibit_rules — do not edit; regenerate with:\n"
    "#   python3 tests/ops/test_generated_dedup_inhibit_fixture.py\n"
    "# dedup_configs: ta=enable tb=disable tc=None td=enable (#3899)\n"
)


def render() -> str:
    rules, _notes = generate_inhibit_rules(dict(DEDUP_CONFIGS))
    return _HEADER + yaml.safe_dump({"inhibit_rules": rules}, sort_keys=False,
                                    default_flow_style=False, allow_unicode=True)


def test_fixture_is_the_generators_output():
    assert FIXTURE.is_file(), (
        f"{FIXTURE.relative_to(REPO)} is missing; run: "
        "python3 tests/ops/test_generated_dedup_inhibit_fixture.py")
    assert FIXTURE.read_text(encoding="utf-8") == render(), (
        f"{FIXTURE.relative_to(REPO)} is not what generate_inhibit_rules renders "
        "now; run: python3 tests/ops/test_generated_dedup_inhibit_fixture.py")


def test_fixture_holds_one_dedup_rule_excluding_disable_and_none():
    """The shape the Go semantics rest on: ONE rule, the excluded list is the
    disable and None tenants, both equal labels gated."""
    rules = yaml.safe_load(FIXTURE.read_text(encoding="utf-8"))["inhibit_rules"]
    assert len(rules) == 1, rules
    [rule] = rules
    assert is_generated_dedup_rule(rule)
    assert rule["equal"] == ["tenant", "metric_group"]
    assert rule["source_matchers"] == [
        'severity="critical"', 'metric_group=~".+"', 'tenant=~".+"']
    assert rule["target_matchers"] == [
        'severity="warning"', 'metric_group=~".+"', 'tenant=~".+"',
        'tenant!~"tb|tc"']
    assert find_ungated_equal_label_inhibits(rules) == []


if __name__ == "__main__":
    FIXTURE.parent.mkdir(parents=True, exist_ok=True)
    FIXTURE.write_text(render(), encoding="utf-8")
    print(f"wrote {os.path.relpath(FIXTURE)}")
